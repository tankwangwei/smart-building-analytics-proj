"""Writes docs/VERIFICATION.md and docs/verification_event_sample.csv from the stored outputs.
Run from the project folder: python tests/make_verification_report.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, str(Path(__file__).parents[1] / "dashboard"))
from conftest import FLOORS, OPEN_DEFAULT, OUT, ROOT, read_floor  # noqa: E402
from fm_core import CLOSED_DATES, build_events, flag_detail  # noqa: E402
from verify_analysis import baseline_bias_pct  # noqa: E402
from verify_forecast import ashrae_table, interval_coverage, metrics, pred, rolling_profile_forecast  # noqa: E402


def md(df, floatfmt=".2f"):
    return df.to_markdown(index=False, floatfmt=floatfmt) if hasattr(df, "to_markdown") else df.to_string(index=False)


def building_forecast():
    parts = [pred(f) for f in FLOORS]
    cols = ["floor_kW", "M1 median profile"]
    return sum(p[cols] for p in parts)


def holiday_adjust(series):
    return series.where(~series.index.normalize().isin(CLOSED_DATES), 0.0)


def main():
    flagged = {}
    for f in FLOORS:
        d, th = read_floor(f)
        flagged[f] = flag_detail(d, th, OPEN_DEFAULT, 1.5, 1.5, 0.5, 8)
    lines = ["# Verification of the analysis and forecast (Phase 0)", "",
             "Generated by `python tests/make_verification_report.py`. Automated checks: `pytest tests/verify_analysis.py "
             "tests/verify_forecast.py`.", ""]

    lines += ["## What could not be checked", "",
              "- **Reproduction from the raw 1-minute data (A1, A2 second half):** `combined_by_floor.csv` (618 MB) is not in the "
              "repository, so recomputing energy and peaks from raw minutes was not done. Instead the stored KPIs were "
              "reconciled against the 15-minute detail (see A2 below).",
              "- **Training-year refit and a true leakage audit of M1 (B1):** the Jul 2018 – Jun 2019 loads are not in the "
              "repository either. The audit checks what can be seen: the lag models use only values from >= 24 h / 168 h "
              "earlier, and M1 is one fixed profile over the whole test period (it is not refit on test data).",
              "- **Realistic weather (B6):** re-scoring with Open-Meteo's historical-forecast archive needs network access and "
              "was not run. The weather models still use observed weather, so their accuracy is optimistic.",
              "- **Eyeball precision/recall (A5):** needs a person. `docs/verification_event_sample.csv` lists 20 random flagged "
              "events and 20 random unflagged unit-days (fixed seed) with an empty `judgement` column to fill in.", ""]

    # A2 / A4 / A5
    rows = []
    for f, d in flagged.items():
        kpi = pd.read_csv(OUT / f"floor_{f}" / "floor_reporting_15min_kpis.csv", index_col=0).iloc[:, 0]
        wide = d.pivot_table(index="Date", columns="unit", values="actual_kW", aggfunc="first")
        elig = d.pivot_table(index="Date", columns="unit", values="eligible", aggfunc="first").astype(bool).all(axis=1)
        e = wide[elig].sum().sum() * 0.25
        rows.append({"Floor": f, "Stored kWh": kpi["estimated_energy_kWh_valid_intervals"], "Recomputed kWh": e,
                     "Diff %": 100 * (e / kpi["estimated_energy_kWh_valid_intervals"] - 1),
                     "Stored peak kW": kpi["15min_peak_kW"], "Recomputed peak kW": wide[elig].sum(axis=1).max()})
    lines += ["## A2. Energy reconciliation (stored KPIs vs the 15-minute detail)", "", md(pd.DataFrame(rows).astype({"Floor": str})), ""]

    bias = baseline_bias_pct(flagged).rename("Baseline bias %").reset_index().rename(columns={"index": "Unit"})
    bias["Within ±5%"] = bias["Baseline bias %"].abs() <= 5
    lines += ["## A4. Baseline bias", "",
              "Mean (actual − expected) on open, unflagged weekday intervals, as % of mean power. A negative value means the unit "
              "used less than its baseline year predicts.", "", md(bias, ".1f"), "",
              f"{int((~bias['Within ±5%']).sum())} of {len(bias)} units are outside ±5%. The largest negatives (F3 z1 AC4, F5 z1 AC4, "
              "F3 z5 AC1) used clearly less in Jul–Dec 2019 than in the baseline year. Excess-energy estimates for them are "
              "therefore on the high side, and quiet-period flags on them are less likely. Part of the negative bias is "
              "expected because flagged (high) intervals are excluded.", ""]

    rate = pd.Series({u: p["flagged"].mean() * 100 for d in flagged.values() for u, p in d[d["eligible"]].groupby("unit")})
    lines += ["## A5. Flag rate per unit (% of valid intervals)", "", md(rate.rename("Flagged %").reset_index().rename(
        columns={"index": "Unit"}), ".2f"), "", f"Range {rate.min():.2f}–{rate.max():.2f}%, median {rate.median():.2f}%.", ""]

    rng = np.random.default_rng(42)
    ev = pd.concat([build_events(d).assign(floor=f) for f, d in flagged.items()], ignore_index=True)
    sample = ev.sample(20, random_state=42)[["unit", "start", "end", "pattern", "excess_kWh", "confidence"]].assign(kind="flagged event")
    unf = []
    for f, d in flagged.items():
        days = d[~d["flagged"] & d["eligible"]].groupby(["unit", d["Date"].dt.normalize()]).size().reset_index()
        unf.append(days)
    unf = pd.concat(unf).sample(20, random_state=42)
    unf = pd.DataFrame({"unit": unf["unit"], "start": unf["Date"], "end": unf["Date"] + pd.Timedelta(days=1),
                        "kind": "unflagged day"})
    pd.concat([sample, unf]).assign(judgement="").to_csv(ROOT / "docs" / "verification_event_sample.csv", index=False)

    # B2 / B4
    hol_rows = []
    b = building_forecast().dropna()
    for label, fc in [("without holiday adjustment", b["M1 median profile"]),
                      ("with holiday adjustment (dashboard)", holiday_adjust(b["M1 median profile"]))]:
        hol_rows.append({"Building M1": label, **metrics(b["floor_kW"], fc)})
    lines += ["## B2. Metrics recomputed (building = sum of floors, M1 typical weekly pattern)", "", md(pd.DataFrame(hol_rows)), "",
              "Per-floor metrics recomputed from `forecast_hourly_actual_predictions.csv` equal `forecast_test_metrics.csv` "
              "for every floor and every model (automated test).", ""]

    t = ashrae_table()
    t["Floor"] = t["Floor"].astype(str)
    lines += ["## B4. ASHRAE Guideline 14 (M1, per floor)", "",
              "Criteria: NMBE within ±10%, CV(RMSE) ≤ 30%. Guideline 14 defines these for hourly data (and ±5% / 15% for "
              "monthly); it has no daily criterion, so the hourly limits are applied to daily totals, the lenient reading.",
              "", md(t, ".1f"), "",
              "**The forecast fails the CV(RMSE) criterion at hourly resolution on every floor (about 70–76%) and also on daily "
              "totals (40–44%).** Bias (NMBE) passes on Floors 4, 5 and 7; Floor 3 is marginally over at +10.1%. Present the "
              "forecast as useful for planning (better than repeating last week), not as a calibrated model.", ""]

    # B3 rolling-origin
    roll_rows, brk = [], []
    for f in FLOORS:
        p = pred(f)
        rolled = rolling_profile_forecast(p["floor_kW"])
        idx = rolled.index
        fixed = p["M1 median profile"].reindex(idx)
        act = p["floor_kW"].reindex(idx)
        ok = fixed.notna() & act.notna()
        roll_rows.append({"Floor": f, "Fixed M1 MAE": (fixed[ok] - act[ok]).abs().mean(),
                          "Rolling profile MAE": (rolled[ok] - act[ok]).abs().mean(),
                          "Fixed M1 MAE (holiday adj.)": (holiday_adjust(fixed)[ok] - act[ok]).abs().mean(),
                          "Rolling MAE (holiday adj.)": (holiday_adjust(rolled)[ok] - act[ok]).abs().mean()})
    lines += ["## B3. Rolling-origin backtest (weekly refit, expanding window, from 26 Aug 2019)", "",
              "The rolling model only has Jul–Dec 2019 history (the training year is not available here), so it is a "
              "smaller-sample comparison, not proof either way.", "", md(pd.DataFrame(roll_rows).astype({"Floor": str})), ""]

    fc = holiday_adjust(b["M1 median profile"])
    err = fc - b["floor_kW"]
    hol = b.index.normalize().isin(CLOSED_DATES)
    peak = b["floor_kW"] >= b["floor_kW"].quantile(.9)
    def breakdown(name, key):
        g = pd.DataFrame({"key": key, "abs": err.abs(), "err": err}).groupby("key")
        return pd.DataFrame({"Breakdown": name, "Group": [str(k) for k in g.size().index], "MAE kW": g["abs"].mean().values,
                             "Bias kW": g["err"].mean().values})
    br = pd.concat([breakdown("month", b.index.strftime("%Y-%m")), breakdown("weekday", b.index.strftime("%a")),
                    breakdown("holiday", np.where(hol, "holiday/closure", "normal day")),
                    breakdown("peak hours", np.where(peak, "top 10% hours", "other hours"))])
    hr = breakdown("hour", b.index.hour)
    lines += ["## B3. Error breakdown (building, M1, holiday-adjusted)", "", md(br), "", "By hour of day:", "", md(hr), ""]

    cov = pd.DataFrame({"Floor": FLOORS, "80% interval coverage on Oct–Dec": [interval_coverage(f) for f in FLOORS]})
    lines += ["## B5. 80% prediction interval", "",
              "Empirical error quantiles by hour of day, calibrated on Jul–Sep 2019 and scored on Oct–Dec 2019.", "",
              md(cov.astype({"Floor": str}), ".2f"), "",
              "Coverage is above the nominal 80% because the calibration errors include the large misses on holidays; the band is "
              "conservative (wide), not too narrow.", ""]
    (ROOT / "docs" / "VERIFICATION.md").write_text("\n".join(lines))
    print("wrote docs/VERIFICATION.md")


if __name__ == "__main__":
    main()
